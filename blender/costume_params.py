def ring_point(a, b, yc, th, n=SUPER_N):
    s, c = math.sin(th), math.cos(th)
    x = -a * math.copysign(abs(s) ** (2.0 / n), s)
    y = yc + b * math.copysign(abs(c) ** (2.0 / n), c)
    return x, y


def perimeter(a, b, n=SUPER_N, k=128):
    pts = [ring_point(a, b, 0, 2 * math.pi * i / k, n) for i in range(k + 1)]
    return sum(math.dist(pts[i], pts[i + 1]) for i in range(k))


def profile_arclen(name):
    """沿正面中线（θ=π）从下摆到领口的弧长，返回 [(z, s, perimeter)]，s 从下摆 0 开始。"""
    prof = PROFILES[name]
    pts = [(z, b, yc, a) for z, a, b, yc in prof]
    out = []
    s = 0.0
    rev = list(reversed(pts))
    for i, (z, b, yc, a) in enumerate(rev):
        if i:
            z0, b0, yc0, _ = rev[i - 1]
            s += math.hypot(z - z0, (yc - b) - (yc0 - b0))
        out.append((z, s, perimeter(a, b)))
    return out


